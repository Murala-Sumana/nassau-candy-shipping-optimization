import streamlit as st
import pandas as pd
from pathlib import Path

st.set_page_config(
    page_title="Nassau Candy | Factory & Shipping Optimization",
    page_icon="🍬",
    layout="wide",
)

st.title("🍬 Factory Reallocation & Shipping Optimization")
st.caption("Nassau Candy Distributor • Data analysis and decision-support dashboard")

st.info(
    "This dashboard presents exploratory analysis and proposed recommendations. "
    "It is not an automated factory-allocation optimizer. Review the README for "
    "data-quality concerns and assumptions before using the results."
)

DATA_DIR = Path(__file__).parent

FILES = {
    "Factory recommendations": "factory_recommendations.csv",
    "Factory performance": "factory_performance_summary.csv",
    "Product summary": "product_summary.csv",
    "Model comparison": "model_comparison.csv",
    "Factory–destination distances": "factory_destination_distances.csv",
    "Nearest-factory assignments": "nearest_factory_assignments.csv",
    "Single-factory comparison": "single_factory_distance_comparison.csv",
}

@st.cache_data
def load_csv(path):
    return pd.read_csv(path)

loaded = {}
missing = []
for label, filename in FILES.items():
    path = DATA_DIR / filename
    if path.exists():
        try:
            loaded[label] = load_csv(path)
        except Exception as exc:
            st.warning(f"Could not read {filename}: {exc}")
    else:
        missing.append(filename)

if missing:
    st.warning(
        "Some CSV files are missing. Put these files in the same folder as app.py: "
        + ", ".join(missing)
    )

pages = ["Overview"] + list(loaded.keys()) + ["About & Limitations"]
page = st.sidebar.radio("Navigate", pages)

def show_table(df, key):
    st.dataframe(df, use_container_width=True, hide_index=True)
    csv_bytes = df.to_csv(index=False).encode("utf-8")
    st.download_button(
        "Download this table as CSV",
        data=csv_bytes,
        file_name=f"{key.lower().replace(' ', '_')}.csv",
        mime="text/csv",
    )

if page == "Overview":
    st.subheader("Project overview")
    st.write(
        "Explore factory performance, product-level summaries, model evaluation, "
        "and geographic distance estimates using the project's prepared CSV outputs."
    )

    if "Factory performance" in loaded:
        df = loaded["Factory performance"]
        st.subheader("Factory performance")
        st.dataframe(df, use_container_width=True, hide_index=True)

        numeric_cols = df.select_dtypes(include="number").columns.tolist()
        if numeric_cols:
            metric_options = [c for c in numeric_cols if any(
                term in c.lower() for term in ["sales", "profit", "units", "order", "record"]
            )]
            if metric_options:
                metric = st.selectbox("Compare factories by", metric_options)
                name_candidates = [c for c in df.columns if any(
                    term in c.lower() for term in ["factory", "name"]
                )]
                if name_candidates:
                    name_col = name_candidates[0]
                    chart_df = df[[name_col, metric]].dropna().set_index(name_col)
                    st.bar_chart(chart_df)

    if "Model comparison" in loaded:
        st.subheader("Machine-learning model comparison")
        show_table(loaded["Model comparison"], "model_comparison")

    st.caption(
        "Tip: Use the sidebar to inspect each prepared dataset. Column names and "
        "available charts depend on the CSV files generated by the notebook."
    )

elif page == "About & Limitations":
    st.subheader("About this project")
    st.write(
        "The project analyzes historical distributor data, summarizes factory and "
        "product performance, compares lead-time prediction models, and explores "
        "straight-line distances between selected destinations and assumed factory locations."
    )
    st.subheader("Important limitations")
    st.markdown("""
    - The source data contains date inconsistencies and unusually long calculated shipping lead times.
    - Product-to-factory assignments are proposed/predefined mappings, not outputs from a constrained optimizer.
    - Factory coordinates are assumptions and have not been independently verified.
    - Geographic distances are straight-line estimates, not road distances or actual shipping routes.
    - Geographic analysis covers selected destinations rather than every destination.
    - The analysis does not model factory capacity, inventory, transport prices, or operational constraints.
    - Model scores describe performance on the available dataset and do not guarantee future accuracy.
    """)
    st.subheader("Responsible interpretation")
    st.write(
        "Treat recommendations as exploratory decision support. Validate source data, "
        "factory locations, production capability, inventory, and logistics costs before "
        "making real operational decisions."
    )

else:
    df = loaded[page]
    st.subheader(page)
    st.write(f"Rows: {len(df):,} • Columns: {len(df.columns):,}")

    search = st.text_input("Filter rows (search across text values)", key=f"search_{page}")
    if search:
        mask = df.astype(str).apply(
            lambda col: col.str.contains(search, case=False, na=False)
        ).any(axis=1)
        view_df = df[mask]
    else:
        view_df = df

    st.caption(f"Showing {len(view_df):,} of {len(df):,} rows")
    show_table(view_df, page)

    numeric_cols = view_df.select_dtypes(include="number").columns.tolist()
    if numeric_cols and len(view_df) > 1:
        with st.expander("Quick chart"):
            y_col = st.selectbox("Numeric column", numeric_cols, key=f"y_{page}")
            text_cols = view_df.select_dtypes(exclude="number").columns.tolist()
            if text_cols:
                x_col = st.selectbox("Group/label column", text_cols, key=f"x_{page}")
                chart_data = view_df[[x_col, y_col]].dropna().head(100)
                if not chart_data.empty:
                    st.bar_chart(chart_data.set_index(x_col))
            else:
                st.line_chart(view_df[[y_col]].head(100))
